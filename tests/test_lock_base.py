"""W3: ``lock --check --base REF`` compares with the lock at the base, which a PR cannot re-bless.

A pull request that edits what the agents read can also regenerate ``.ghostrules.lock`` so that
``lock --check`` passes in the working tree. With ``--base`` the lock comes from the reviewed base
commit, and so does the configuration that decides what the snapshot contains.
"""

from pathlib import Path

from pr_helpers import BASE_FILES, EDITED_STYLE, LOCK, lock_text, pull_request, reblessed_pr
from typer.testing import CliRunner

from ghostrules.cli import app


def check(repo: Path, *flags: str) -> tuple[int, str]:
    result = CliRunner().invoke(app, ["lock", "--check", "--root", str(repo), "--no-color", *flags])
    return result.exit_code, result.output


def test_0_3_default_lets_the_pr_re_bless_its_own_change(tmp_path: Path) -> None:
    repo, _ = reblessed_pr(tmp_path)
    code, out = check(repo)
    assert code == 0, out  # the lock in the working tree was regenerated by the PR


def test_base_compares_with_the_lock_at_the_base(tmp_path: Path) -> None:
    repo, base = reblessed_pr(tmp_path)
    code, out = check(repo, "--base", base)
    assert code == 1, out
    assert "docs/style.md" in out and "bootstrap.sh" in out  # the diff a reviewer needs


def test_base_passes_when_what_the_agents_read_did_not_change(tmp_path: Path) -> None:
    repo, base = pull_request(
        tmp_path / "w",
        {**BASE_FILES, LOCK: lock_text(tmp_path, BASE_FILES)},
        {"README.md": "# Project\n"},
    )
    code, out = check(repo, "--base", base)
    assert code == 0, out


def test_a_base_without_a_lock_is_a_clear_error_not_a_pass(tmp_path: Path) -> None:
    repo, base = pull_request(tmp_path / "w", BASE_FILES, {LOCK: lock_text(tmp_path, BASE_FILES)})
    code, out = check(repo, "--base", base)
    assert code == 2
    assert base[:7] in out or "base" in out
    assert "no .ghostrules.lock" in out and "ghostrules lock" in out


def test_an_unknown_base_is_an_error_naming_it(tmp_path: Path) -> None:
    repo, _ = reblessed_pr(tmp_path)
    code, out = check(repo, "--base", "no-such-ref")
    assert code == 2 and "no-such-ref" in out


def test_the_pr_cannot_move_the_lock_with_its_own_config(tmp_path: Path) -> None:
    """``lockfile = "evil.lock"`` in the PR's config must not redirect the comparison."""
    head = {**BASE_FILES, "docs/style.md": EDITED_STYLE}
    repo, base = pull_request(
        tmp_path / "w",
        {**BASE_FILES, LOCK: lock_text(tmp_path, BASE_FILES, "b")},
        {
            "docs/style.md": EDITED_STYLE,
            ".ghostrules.toml": 'lockfile = "evil.lock"\n',
            "evil.lock": lock_text(tmp_path, head, "h"),
        },
    )
    code, out = check(repo, "--base", base)
    assert code == 1, out


def test_the_pr_cannot_shrink_the_snapshot_with_its_own_agents(tmp_path: Path) -> None:
    """``agents = [...]`` in the PR's config would hide the change from the agent that reads it."""
    only_cursor = 'agents = ["cursor"]\n'
    head = {**BASE_FILES, "docs/style.md": EDITED_STYLE, ".ghostrules.toml": only_cursor}
    repo, base = pull_request(
        tmp_path / "w",
        {**BASE_FILES, LOCK: lock_text(tmp_path, BASE_FILES, "b")},
        {
            "docs/style.md": EDITED_STYLE,
            ".ghostrules.toml": only_cursor,
            LOCK: lock_text(tmp_path, head, "h"),
        },
    )
    code, out = check(repo, "--base", base)
    assert code == 1, out
    assert "docs/style.md" in out


def test_base_needs_check_and_excludes_config(tmp_path: Path) -> None:
    repo, base = reblessed_pr(tmp_path)
    assert CliRunner().invoke(app, ["lock", "--root", str(repo), "--base", base]).exit_code == 2
    trusted = tmp_path / "c.toml"
    trusted.write_text("", encoding="utf-8")
    code, out = check(repo, "--base", base, "--config", str(trusted))
    assert code == 2 and "cannot be used together" in out
