ZWSP, ZWNJ = chr(0x200B), chr(0x200C)
RLO, LRI, PDI = chr(0x202E), chr(0x2066), chr(0x2069)
CYRILLIC_A, CYRILLIC_O = chr(0x0430), chr(0x043E)

# Defanged payloads hidden in the other invisible encodings.
