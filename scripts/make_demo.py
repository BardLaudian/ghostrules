def tag(text: str) -> str:
    """Encode ASCII as invisible Unicode tag characters (U+E0000 + code point)."""
    return "".join(chr(0xE0000 + ord(c)) for c in text)


def zero_width(text: str) -> str:
    """Encode text as bits: zero-width space = 0, zero-width non-joiner = 1."""
    bits = "".join(f"{byte:08b}" for byte in text.encode())
    return "".join(ZWNJ if bit == "1" else ZWSP for bit in bits)


def variation_selectors(text: str) -> str:
    """Encode bytes as variation selectors (0-15 -> U+FE00.., 16-255 -> U+E0100..)."""
    return "".join(chr(0xFE00 + b) if b < 16 else chr(0xE0100 + b - 16) for b in text.encode())


def _write(root: Path, rel: str, content: str) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")


def _json(data: object) -> str:
    return json.dumps(data, indent=2) + "\n"


